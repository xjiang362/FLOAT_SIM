%% makeFullStateTables.m
% Emits two LaTeX files for the full-state delay-aware LQI design:
%
%   fullstate_matrices_table.tex   every numerical matrix of the plant,
%                                  measurement chain and controller
%   fullstate_design_writeup.tex   the derivation check and the weight
%                                  selection process, as prose + tables
%
% Both are standalone and can be pasted into Overleaf. They need
% \usepackage{booktabs}, \usepackage{amsmath} and \usepackage{siunitx}.
%
% See also TRAPFULLSTATEMODEL, SELECTFULLSTATEWEIGHTS, SIMULATEFULLSTATELQI.

clear; clc;
root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'config'), fullfile(root,'dynamics'), ...
        fullfile(root,'control'), fullfile(root,'estimator'), ...
        fullfile(root,'presentation'), root);

p = trapDeviceGeometry();
M = trapFullStateModel(p, 'rhoU', 1e2, 'rhoI', 1e2, 'rMeas', 1e-2);
m = p.mass.m; Ix = p.mass.I(1,1); Iy = p.mass.I(2,2);
pz = M.omega(1);

%% ================= file 1: matrices =================
f = fopen(fullfile(root,'presentation','fullstate_matrices_table.tex'),'w');
fprintf(f,'%% Generated by presentation/makeFullStateTables.m -- do not edit by hand.\n');
fprintf(f,'%% Requires \\usepackage{amsmath}, \\usepackage{booktabs}.\n\n');

fprintf(f,'\\subsection{Numerical model}\n\n');
fprintf(f,'All matrices below are at $T_{\\mathrm{ISR}}=\\SI{%.0f}{\\micro\\second}$,\n',M.T*1e6);
fprintf(f,'$L_c=\\SI{%.0f}{\\micro\\metre}$, channel ages\n',M.Lc*1e6);
fprintf(f,'$\\{%.0f,\\,%.0f,\\,%.0f,\\,%.0f\\}\\,\\si{\\micro\\second}$ and residual delays\n', M.age*1e6);
fprintf(f,'$\\delta=\\{%.0f,\\,%.0f,\\,%.0f,\\,%.0f\\}\\,\\si{\\micro\\second}$.\n\n', M.delta*1e6);

fprintf(f,'\\paragraph{Modal constants.}\n');
fprintf(f,'\\begin{table}[htbp]\n  \\centering\n');
fprintf(f,'  \\caption{Modal constants of the open-loop plant. $k_j>0$ is anti-restoring.}\n');
fprintf(f,'  \\begin{tabular}{lSSSS}\n    \\toprule\n');
fprintf(f,'    Mode & {$k_j$} & {$\\sigma_j$ [\\si{\\per\\second}]} & {$\\kappa_j$ [\\si{\\per\\second\\squared}]} & {$\\omega_j$ [\\si{\\radian\\per\\second}]} \\\\\n    \\midrule\n');
nmj = {'$z$ (heave)','$\\theta_x$ (roll)','$\\theta_y$ (pitch)'};
for j=1:3
    fprintf(f,'    %s & %.5e & %.6e & %.6e & %.4f \\\\\n', nmj{j}, M.k(j), M.sigma(j), M.kappa(j), M.omega(j));
end
fprintf(f,'    \\bottomrule\n  \\end{tabular}\n\\end{table}\n\n');

emit(f,'A_c',       M.Ac,   '%.5g', 'continuous plant matrix');
emit(f,'A_d',       M.Ad,   '%.6f', 'discrete plant, $A_d=e^{A_cT}$');
emit(f,'B_d',       M.Bd,   '%.5e', 'discrete input, $B_d=\int_0^T e^{A_cs}B_c\,ds$');
emit(f,'\Phi',      M.Phi,  '%.5f', 'delayed-channel state rows');
emit(f,'\Gamma',    M.Gam,  '%.5e', 'delayed-channel input rows');
emit(f,'\Phi_4',    M.Phi4, '%.5f', 'in-frame channel state row');
emit(f,'\Gamma_4',  M.Gam4, '%.5e', 'in-frame channel input row');
emit(f,'H',         M.H,    '%.5g', 'output-to-pose map');
emit(f,'K_x',       M.Kx,   '%.5e', 'regulator gain on $\hat{x}$');
emit(f,'K_z',       M.Kz,   '%.5e', 'regulator gain on $\hat{z}$');
emit(f,'K_u',       M.Ku,   '%.5f', 'regulator gain on $u[k-1]$');
emit(f,'K_I',       M.KI,   '%.5e', 'integrator gain');
emit(f,'L',         M.L,    '%.5e', 'observer gain');
fclose(f);

%% ================= file 2: writeup =================
f = fopen(fullfile(root,'presentation','fullstate_design_writeup.tex'),'w');
fprintf(f,'%% Generated by presentation/makeFullStateTables.m -- do not edit by hand.\n');
fprintf(f,'%% Requires \\usepackage{amsmath}, \\usepackage{booktabs}, \\usepackage{siunitx}.\n\n');

fprintf(f,'\\subsection{Verification of the closed-form model}\n\n');
fprintf(f,'Every closed form in the derivation was checked against a numerical\n');
fprintf(f,'matrix exponential and quadrature at the four delays used here.\n');
fprintf(f,'$E_j(\\delta)$ reproduces $e^{-A_c\\delta}$ and $g_j(\\delta)$ reproduces\n');
fprintf(f,'$\\int_0^{\\delta}e^{-A_cs}B_c\\,ds$ to a relative error below\n');
fprintf(f,'$5\\times10^{-16}$, and $A_d,B_d$ match \\texttt{c2d} to the same order.\n');
fprintf(f,'Two corrections were required.\n\n');

fprintf(f,'\\paragraph{(i) The $\\omega_j$ definition.} As written,\n');
fprintf(f,'$\\omega_x=\\sqrt{(q_x/2m)^2+k_x/I_x}$ mixes the plate mass into a\n');
fprintf(f,'rotational mode; it should be $\\omega_x=\\sqrt{(q_x/2I_x)^2+k_x/I_x}$,\n');
fprintf(f,'so that $\\omega_j^2=\\sigma_j^2+\\kappa_j$ consistently. Numerically the\n');
fprintf(f,'difference is $4\\times10^{-9}$ here because $\\sigma_j^2\\ll\\kappa_j$, so no\n');
fprintf(f,'result changes, but the expression is still wrong as printed.\n');
fprintf(f,'The same substitution applies to $\\omega_y$. Separately, $A_c$ uses a\n');
fprintf(f,'single $k_\\theta$ for both tilts while the $\\kappa$ definitions use\n');
fprintf(f,'$k_x$ and $k_y$; the two tilt stiffnesses differ by \\SI{10}{\\percent}\n');
fprintf(f,'($\\SI{-7.713e-5}{}$ versus $\\SI{-8.526e-5}{\\newton\\metre\\per\\radian}$)\n');
fprintf(f,'and must be kept distinct.\n\n');

fprintf(f,'\\paragraph{(ii) The pairing of $\\Phi$ and $\\Gamma$.} The update\n');
fprintf(f,'$z[k+1]=\\Phi x[k]+\\Gamma u[k]$ with $\\Phi_i=C_ie^{-A_c\\delta_i}$ is not\n');
fprintf(f,'self-consistent. Since $e^{-A_c\\delta}$ propagates \\emph{backward},\n');
fprintf(f,'$\\Phi_ix[k]$ is the channel sampled at $t_k-\\delta_i$, which precedes\n');
fprintf(f,'frame $k$ and therefore cannot carry $u[k]$. Checked against a\n');
fprintf(f,'brute-force integration, the row as written is wrong by\n');
fprintf(f,'\\SIrange{13}{38}{\\percent} at the delays used here.\n\n');
fprintf(f,'A channel delivered at $t_{k+1}$ with age $\\delta_i$ was sampled at\n');
fprintf(f,'$t_k+(T-\\delta_i)$, inside frame $k$, so the consistent rows are\n');
fprintf(f,'\\begin{equation}\n');
fprintf(f,'  \\Phi_i=C_ie^{A_c(T-\\delta_i)}=\\Phi_i^{\\mathrm{note}}A_d,\\qquad\n');
fprintf(f,'  \\Gamma_i=C_i\\!\\!\\int_0^{T-\\delta_i}\\!\\!\\!e^{A_cs}B_c\\,ds\n');
fprintf(f,'          =\\Phi_i^{\\mathrm{note}}B_d+\\Gamma_i^{\\mathrm{note}}\n');
fprintf(f,'\\end{equation}\n');
fprintf(f,'i.e.\\ the original matrices are right up to one further step of\n');
fprintf(f,'propagation. Both corrected forms reproduce the brute-force sample to\n');
fprintf(f,'$2\\times10^{-16}$. Keeping $\\Phi^{\\mathrm{note}}$ and pairing it with\n');
fprintf(f,'$u[k-1]$ instead is also self-consistent, but describes a schedule one\n');
fprintf(f,'frame longer.\n\n');

fprintf(f,'\\subsection{Weight selection}\n\n');
fprintf(f,'Both gains come from a discrete Riccati solve: the regulator from\n');
fprintf(f,'$\\mathrm{dlqr}(\\bar{A}_\\chi,\\bar{B}_\\chi,Q,R)$ with\n');
fprintf(f,'$Q=\\operatorname{blkdiag}(I_6,0,0,\\rho_I I_3)$ and $R=\\rho_u I_3$, and\n');
fprintf(f,'the observer from the dual $\\mathrm{dlqr}(\\bar{A}^\\top,\\bar{C}^\\top,Q_o,R_o)^\\top$\n');
fprintf(f,'with $Q_o=q\\,I_9$, $R_o=r\\,I_4$.\n\n');
fprintf(f,'The solve is performed on a \\emph{non-dimensionalised} system. The raw\n');
fprintf(f,'state mixes metres with radians and positions with rates over six\n');
fprintf(f,'orders of magnitude, giving $\\operatorname{cond}(\\mathcal{C})=%.2e$;\n', M.condRegRaw);
fprintf(f,'after scaling each state by its characteristic magnitude this falls to\n');
fprintf(f,'$%.2e$, and the observer pair from $%.2e$ to $%.2e$.\n\n', ...
    M.condRegScaled, M.condObsRaw, M.condObsScaled);

fprintf(f,'\\paragraph{The binding constraints are physical, not spectral.}\n');
fprintf(f,'Two limits dominate the choice. First, the actuator is\n');
fprintf(f,'\\emph{unilateral}: it can only pull the plate toward the electrodes,\n');
fprintf(f,'so the most negative achievable acceleration is $-g$, while upward it\n');
fprintf(f,'reaches $+\\SI{217}{\\metre\\per\\second\\squared}$ at\n');
fprintf(f,'$V_{\\max}=\\SI{120}{\\volt}$. Second, the plate has only\n');
fprintf(f,'$\\pm\\SI{15}{\\micro\\metre}$ of travel, so a transient that overshoots\n');
fprintf(f,'that is useless however well damped it is on paper.\n\n');

fprintf(f,'\\begin{table}[htbp]\n  \\centering\n');
fprintf(f,'  \\caption{Control-weight sweep at $\\rho_I=10^{2}$, $r=10^{-2}$, released\n');
fprintf(f,'           from $r_z=\\SI{-5}{\\micro\\metre}$. The peak excursion exceeds the\n');
fprintf(f,'           \\SI{15}{\\micro\\metre} wall for every weight, so the nonlinear\n');
fprintf(f,'           plant contacts in all cases.}\n');
fprintf(f,'  \\begin{tabular}{SSSSSl}\n    \\toprule\n');
fprintf(f,'    {$\\rho_u$} & {$\\max|z|$} & {BW [\\si{\\hertz}]} & {peak $a_z$ [\\si{\\metre\\per\\second\\squared}]} & {peak $r_z$ [\\si{\\micro\\metre}]} & Plant \\\\\n    \\midrule\n');
sw = {1e-2,0.2309,324.0,434.81,30.19,'contact \\SI{1.4}{\\milli\\second}'; ...
      1e-1,0.2643,294.2,424.52,29.67,'contact \\SI{1.4}{\\milli\\second}'; ...
      1e0 ,0.3537,229.7,363.02,26.47,'contact \\SI{1.4}{\\milli\\second}'; ...
      1e1 ,0.4670,168.3,234.74,26.13,'contact \\SI{1.5}{\\milli\\second}'; ...
      1e2 ,0.5617,127.5,130.50,26.18,'contact \\SI{1.7}{\\milli\\second}'; ...
      1e3 ,0.6366, 99.8, 77.16,22.18,'contact \\SI{2.0}{\\milli\\second}'; ...
      1e4 ,0.8584, 33.8, 62.66,19.22,'contact \\SI{2.4}{\\milli\\second}'};
for i=1:size(sw,1)
    fprintf(f,'    %.0e & %.4f & %.1f & %.2f & %.2f & %s \\\\\n', sw{i,:});
end
fprintf(f,'    \\bottomrule\n  \\end{tabular}\n\\end{table}\n\n');

fprintf(f,'\\paragraph{Why no weight succeeds.} The peak excursion is almost\n');
fprintf(f,'independent of $\\rho_u$, varying only between \\SI{19}{} and\n');
fprintf(f,'\\SI{30}{\\micro\\metre} across six decades of control weight. That\n');
fprintf(f,'insensitivity is the signature of a \\emph{delay} limit rather than a\n');
fprintf(f,'tuning one. With the plate released at $r_z=\\SI{-5}{\\micro\\metre}$ the\n');
fprintf(f,'open-loop mode grows as $\\cosh(p_zt)$ with\n');
fprintf(f,'$p_z=\\SI{%.1f}{\\radian\\per\\second}$:\n', pz);
fprintf(f,'\\begin{center}\n\\begin{tabular}{lSS}\n\\toprule\n');
fprintf(f,'Event & {$t$ [\\si{\\milli\\second}]} & {$r_z$ [\\si{\\micro\\metre}]} \\\\\n\\midrule\n');
fprintf(f,'Channel 4 arrives & 0.59 & -6.18 \\\\\n');
fprintf(f,'Channel 1 arrives & 1.13 & -9.79 \\\\\n');
fprintf(f,'Plate reaches the wall & 1.54 & -15.00 \\\\\n');
fprintf(f,'\\bottomrule\n\\end{tabular}\n\\end{center}\n');
fprintf(f,'The first usable measurement lands at \\SI{1.13}{\\milli\\second}, by which\n');
fprintf(f,'time the plate is already at \\SI{-9.8}{\\micro\\metre} and moving at\n');
fprintf(f,'\\SI{-9.6}{\\milli\\metre\\per\\second}; it strikes the wall\n');
fprintf(f,'\\SI{0.41}{\\milli\\second} later. No causal controller recovers from that,\n');
fprintf(f,'which is consistent with $p_zt_d=%.2f>1$.\n\n', pz*max(M.age));
fprintf(f,'The fractional-delay model is therefore necessary but not sufficient:\n');
fprintf(f,'it makes the \\emph{linear} loop stable, where a delay-ignorant design is\n');
fprintf(f,'not, but the stabilising transient exceeds the physical travel. The\n');
fprintf(f,'design becomes usable only once $t_d$ is reduced; at the present\n');
fprintf(f,'$t_{\\mathrm{I2C}}=\\SI{500}{\\micro\\second}$ it is not.\n');
fclose(f);

fprintf('Wrote presentation/fullstate_matrices_table.tex\n');
fprintf('Wrote presentation/fullstate_design_writeup.tex\n');

% =====================================================================
function emit(f, name, Mx, fmt, cap)
fprintf(f,'\\paragraph{$%s$} %s.\n', name, cap);
fprintf(f,'\\begin{equation}\n  %s=\\begin{bmatrix}\n', name);
for i = 1:size(Mx,1)
    fprintf(f,'    ');
    for j = 1:size(Mx,2)
        fprintf(f, fmt, Mx(i,j));
        if j < size(Mx,2), fprintf(f,' & '); end
    end
    if i < size(Mx,1), fprintf(f,' \\\\\n'); else, fprintf(f,'\n'); end
end
fprintf(f,'  \\end{bmatrix}\n\\end{equation}\n\n');
end
