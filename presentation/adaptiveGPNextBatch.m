%% adaptiveGPNextBatch.m
% Fits a Gaussian Process surrogate to each force/torque output from
% the completed COMSOL batch, then proposes the next batch of points
% to run -- selected from a large pool of valid candidate poses by
% predicted uncertainty (highest first), with a minimum-distance
% diversity filter so the batch doesn't cluster in one region.
%
% This is the "start with N points, GP-guided infill from there"
% adaptive sampling strategy: cheaper than committing to a large fixed
% batch upfront, since new points are only spent where the surrogate
% is least confident.

clear; clc;
scriptDir = fileparts(mfilename('fullpath'));
addpath(scriptDir);

%% 1. Load all completed results so far (auto-combines every
% comsol_*_results.txt batch found in this folder)
data = loadAllComsolResults();

inputNames  = {'rx', 'ry', 'rz', 'thx', 'thy', 'thz'};
outputNames = {'Fx', 'Fy', 'Fz', 'Taux', 'Tauy', 'Tauz'};   % primary physical outputs

X = table2array(data(:, inputNames));   % [N x 6]

%% 2. Fit one GP per output (standardized inputs AND outputs -- fitrgp's
% 'Standardize' only normalizes X, not y, and several of these outputs
% have raw magnitudes as small as 1e-8, which made the optimizer
% collapse to a degenerate zero-signal fit when tried on raw y. Fitting
% on z-scored y also means every output's predicted std ends up on a
% comparable O(1) scale, so no separate cross-output normalization is
% needed when combining them below.
gprModels = struct();
yMean = struct();
yStd  = struct();
for i = 1:numel(outputNames)
    y = data.(outputNames{i});
    yMean.(outputNames{i}) = mean(y);
    yStd.(outputNames{i})  = std(y);
    yNorm = (y - yMean.(outputNames{i})) / yStd.(outputNames{i});
    gprModels.(outputNames{i}) = fitrgp(X, yNorm, ...
        'KernelFunction', 'ardsquaredexponential', ...
        'Standardize', true, ...
        'BasisFunction', 'constant');
end
fprintf('Fitted GPs for: %s\n', strjoin(outputNames, ', '));

%% 3. Large pool of valid candidate poses (respects the same
% geometric/collision constraints as the training data, since it's
% generated by the same sampling function)
nCandidates = 3000;
[cx, cy, cz, cthx, cthy, cthz] = sampleTrapPoseLHS(nCandidates);
Xcand = [cx, cy, cz, cthx, cthy, cthz];

%% 4. Predicted uncertainty (std) per output in normalized-y space --
% already comparable across outputs since each was z-scored before
% fitting, so no further cross-output rescaling is needed. Diagnostic
% printout included since a poorly-conditioned fit is a real risk at
% this sample size (40 points in 6D).
%
% Fx and Tauz are excluded from the combined score: they consistently
% fit as near-zero-signal (sigmaF collapses regardless of basis
% function choice), consistent with being weak, simple/near-linear
% restoring terms (Fx~rx, Tauz~thz) that the initial 40-point spread
% likely already constrains adequately -- adaptive sampling is more
% valuable spent on outputs with genuine detectable nonlinear structure.
scoredOutputs = {'Fy', 'Fz', 'Taux', 'Tauy'};

combinedScore = zeros(nCandidates, 1);
fprintf('\n%8s  %12s  %12s  %12s  %8s\n', 'output', 'sigmaF', 'min pred sd', 'max pred sd', 'in score');
for i = 1:numel(outputNames)
    mdl = gprModels.(outputNames{i});
    [~, ySd] = predict(mdl, Xcand);
    sigmaF = mdl.KernelInformation.KernelParameters(end);   % fitted signal std (normalized-y units)
    isScored = ismember(outputNames{i}, scoredOutputs);
    fprintf('%8s  %12.4g  %12.4g  %12.4g  %8s\n', outputNames{i}, sigmaF, min(ySd), max(ySd), string(isScored));
    if isScored
        combinedScore = combinedScore + ySd;
    end
end

%% 5. Greedy diversity-filtered top-K selection: rank by uncertainty,
% but skip candidates too close (in normalized input space) to a
% point already selected, so the batch doesn't cluster in one region
nBatch = 15;
boundsScale = max(abs(Xcand), [], 1);   % per-dimension scale for normalization
Xnorm = Xcand ./ boundsScale;
minNormDist = 0.15;                     % skip candidates closer than this to an already-picked point

[~, order] = sort(combinedScore, 'descend');
selected = false(nCandidates, 1);
nPicked = 0;
for idx = order'
    if nPicked >= nBatch
        break;
    end
    if nPicked == 0 || all(vecnorm(Xnorm(selected, :) - Xnorm(idx, :), 2, 2) > minNormDist)
        selected(idx) = true;
        nPicked = nPicked + 1;
    end
end

batchIdx = find(selected);
fprintf('Selected %d points for the next batch (from %d candidates)\n', nPicked, nCandidates);

%% 6. Export next batch in the same COMSOL import format. Batch number
% auto-increments past whatever comsol_lhs_batchN.txt files already
% exist (batch 1 is conceptually the initial 40-point set), so reruns
% of this script don't silently overwrite a previous proposed batch.
existing = dir(fullfile(scriptDir, 'comsol_lhs_batch*.txt'));
usedNums = 1;   % initial40 counts as batch 1
for i = 1:numel(existing)
    tok = regexp(existing(i).name, 'comsol_lhs_batch(\d+)\.txt', 'tokens', 'once');
    if ~isempty(tok)
        usedNums(end+1) = str2double(tok{1}); %#ok<AGROW>
    end
end
nextBatchNum = max(usedNums) + 1;

paramNames = {'rx', 'ry', 'rz', 'thx', 'thy', 'thz'};
paramUnits = {'m', 'm', 'm', 'deg', 'deg', 'deg'};
paramData  = {Xcand(batchIdx,1), Xcand(batchIdx,2), Xcand(batchIdx,3), ...
              Xcand(batchIdx,4), Xcand(batchIdx,5), Xcand(batchIdx,6)};

outFile = fullfile(scriptDir, sprintf('comsol_lhs_batch%d.txt', nextBatchNum));
writeComsolParamFile(outFile, paramNames, paramUnits, paramData);
fprintf('Saved next batch to %s\n', outFile);

%% 7. Summary table
fprintf('\n%4s  %10s %10s %10s %10s %10s %10s  %10s\n', ...
    'idx', 'rx(um)', 'ry(um)', 'rz(um)', 'thx(deg)', 'thy(deg)', 'thz(deg)', 'score');
for k = 1:numel(batchIdx)
    i = batchIdx(k);
    fprintf('%4d  %10.3f %10.3f %10.3f %10.4f %10.4f %10.4f  %10.3f\n', ...
        k, Xcand(i,1)*1e6, Xcand(i,2)*1e6, Xcand(i,3)*1e6, ...
        Xcand(i,4), Xcand(i,5), Xcand(i,6), combinedScore(i));
end
